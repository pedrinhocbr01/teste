-- ============================================================================
--  PDV RESTAURANTE — Schema inicial (PostgreSQL 15+)
--  Módulos: Estoque + Ficha Técnica | Atendimento (Garçom) | Caixa & Mesas
--
--  Convenções:
--  • Dinheiro: NUMERIC(12,2). Quantidades de estoque: NUMERIC(12,3)
--    (essencial em restaurante: gramas, ml, frações de kg/litro).
--  • Preços viram "snapshot" nos itens do pedido (mudar o cardápio não
--    altera contas abertas).
--  • O saldo de estoque NUNCA é editado direto: é a soma dos movimentos
--    (fonte da verdade auditável: compra, venda, perda, ajuste).
--  • A baixa automática por venda roda em trigger quando o item é ENVIADO
--    (configurável: ENVIO | PRONTO | ENTREGA) e é estornada se o item for
--    cancelado depois.
--  • PKs bigint (simples de começar). Se um dia houver multi-filia ou
--    sincronização offline, migrar p/ UUID (gen_random_uuid()).
-- ============================================================================

BEGIN;

-- ----------------------------------------------------------------------------
-- 0. ENUMS
-- ----------------------------------------------------------------------------
CREATE TYPE tipo_unidade          AS ENUM ('MASSA', 'VOLUME', 'UNIDADE');
CREATE TYPE tipo_movimento_estoque AS ENUM (
  'ENTRADA',            -- compra recebida
  'SAIDA_VENDA',        -- baixa automática por venda (via ficha técnica)
  'AJUSTE_POSITIVO',    -- contagem de estoque (sobrou)
  'AJUSTE_NEGATIVO',    -- contagem de estoque (faltou)
  'PERDA',              -- estragou, venceu, caiu no chão
  'CONSUMO_INTERNO'     -- refeição de funcionário, teste de cozinha
);
CREATE TYPE tipo_origem_movimento  AS ENUM (
  'COMPRA_FORNECEDOR', 'BAIXA_VENDA', 'CONTAGEM', 'CANCELAMENTO_ITEM', 'OUTRO'
);
CREATE TYPE tipo_status_mesa       AS ENUM ('LIVRE', 'OCUPADA', 'AGUARDANDO_CONTA', 'RESERVADA');
CREATE TYPE tipo_status_pedido     AS ENUM ('ABERTO', 'FECHADO', 'CANCELADO');
CREATE TYPE tipo_status_item       AS ENUM ('RASCUNHO', 'ENVIADO', 'EM_PREPARO', 'PRONTO', 'ENTREGUE', 'CANCELADO');
CREATE TYPE tipo_remessa           AS ENUM ('ENTRADA', 'PRINCIPAL', 'SOBREMESA', 'LIVRE');
CREATE TYPE tipo_status_remessa    AS ENUM ('ENVIADA', 'CONCLUIDA', 'CANCELADA');
CREATE TYPE tipo_estacao           AS ENUM ('COZINHA', 'BAR');
CREATE TYPE tipo_status_impressao  AS ENUM ('PENDENTE', 'EM_IMPRESSAO', 'IMPRESSA', 'FALHA');
CREATE TYPE tipo_status_conta      AS ENUM ('ABERTA', 'FECHADA', 'CANCELADA');
CREATE TYPE tipo_forma_pagamento   AS ENUM ('DINHEIRO', 'PIX', 'CARTAO_CREDITO', 'CARTAO_DEBITO', 'VALE_ALIMENTACAO', 'VALE_REFEICAO', 'OUTRO');
CREATE TYPE tipo_status_pagamento  AS ENUM ('PENDENTE', 'APROVADO', 'CANCELADO');
CREATE TYPE tipo_status_caixa      AS ENUM ('ABERTO', 'FECHADO');
CREATE TYPE tipo_movimento_caixa   AS ENUM ('SANGRIA', 'SUPRIMENTO');
CREATE TYPE tipo_papel_usuario     AS ENUM ('GARCOM', 'CAIXA', 'COZINHEIRO', 'BAR', 'GERENTE', 'ADMIN');

-- ----------------------------------------------------------------------------
-- 1. BASE / CADASTROS
-- ----------------------------------------------------------------------------
CREATE TABLE usuario (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome          TEXT NOT NULL,
  email         TEXT,
  pin_hash      TEXT,                                  -- PIN p/ operar o PDV (hash bcrypt no backend)
  papel         tipo_papel_usuario NOT NULL,
  ativo         BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em     TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- login por e-mail exige unicidade (nulos = usuário sem e-mail, ok repetir)
CREATE UNIQUE INDEX ux_usuario_email ON usuario (lower(email)) WHERE email IS NOT NULL;

-- Configuração única do restaurante (linha id=1)
CREATE TABLE config_restaurante (
  id                  BIGINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  nome                TEXT NOT NULL DEFAULT 'Meu Restaurante',
  gorjeta_percentual  NUMERIC(5,2) NOT NULL DEFAULT 10.00, -- % sugerido de serviço
  gorjeta_incluir_por_padrao BOOLEAN NOT NULL DEFAULT TRUE,
  baixa_estoque_em    TEXT NOT NULL DEFAULT 'ENVIO'
                      CHECK (baixa_estoque_em IN ('ENVIO', 'PRONTO', 'ENTREGA')),
  tempo_medio_prato_min INT  NOT NULL DEFAULT 25          -- p/ alertas de atraso
);

CREATE TABLE unidade_medida (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sigla     TEXT NOT NULL UNIQUE,            -- g, kg, ml, l, un, dz
  nome      TEXT NOT NULL,
  tipo      tipo_unidade NOT NULL
);

CREATE TABLE fornecedor (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome              TEXT NOT NULL,
  cnpj              TEXT,
  telefone          TEXT,
  email             TEXT,
  prazo_entrega_dias SMALLINT,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE
);

-- ----------------------------------------------------------------------------
-- 2. MÓDULO ESTOQUE
-- ----------------------------------------------------------------------------
CREATE TABLE insumo (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome                TEXT NOT NULL,
  unidade_estoque_id  BIGINT NOT NULL REFERENCES unidade_medida (id), -- unidade "base" (kg, l, un)
  unidade_compra_id   BIGINT REFERENCES unidade_medida (id),          -- unidade de compra (fardo, saco, cx)
  fator_compra        NUMERIC(12,3) NOT NULL DEFAULT 1
                      CHECK (fator_compra > 0),  -- 1 unidade de compra = fator_compra unidades de estoque
  custo_unitario      NUMERIC(12,4) NOT NULL DEFAULT 0,  -- custo POR UNIDADE DE ESTOQUE (atualizado nas compras)
  estoque_minimo      NUMERIC(12,3) NOT NULL DEFAULT 0,  -- alerta de falta
  estoque_maximo      NUMERIC(12,3),                     -- p/ sugerir qtd de compra
  fornecedor_padrao_id BIGINT REFERENCES fornecedor (id),
  valido_dias         SMALLINT,                           -- vida útil média (p/ previsão de compra)
  ativo               BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_insumo_nome ON insumo (lower(nome)) WHERE ativo;

CREATE TABLE estoque_movimento (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  insumo_id       BIGINT NOT NULL REFERENCES insumo (id),
  tipo            tipo_movimento_estoque NOT NULL,
  quantidade      NUMERIC(12,3) NOT NULL CHECK (quantidade > 0), -- SEMPRE positiva; o sinal vem do tipo
  custo_unitario  NUMERIC(12,4),                                 -- custo da unidade de estoque na época
  origem          tipo_origem_movimento NOT NULL DEFAULT 'OUTRO',
  pedido_item_id  BIGINT,          -- preenchido pela baixa de venda (FK adicionada após criar pedido_item)
  usuario_id      BIGINT REFERENCES usuario (id),
  motivo          TEXT,            -- ex.: "Nota Fiscal 1023", "Marmita da equipe", "Item 43 cancelado"
  data_movimento  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_estoque_mov_insumo_data ON estoque_movimento (insumo_id, data_movimento DESC);
CREATE INDEX ix_estoque_mov_pedido_item ON estoque_movimento (pedido_item_id) WHERE pedido_item_id IS NOT NULL;

-- ----------------------------------------------------------------------------
-- 3. CARDAPIO + FICHA TECNICA
-- ----------------------------------------------------------------------------
CREATE TABLE estacao (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome          TEXT NOT NULL,                    -- "Cozinha Quente", "Bar"
  tipo          tipo_estacao NOT NULL,            -- COZINHA | BAR (define a fila de impressão)
  ativo         BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE impressora (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estacao_id    BIGINT NOT NULL REFERENCES estacao (id),
  nome          TEXT NOT NULL,                    -- "TM-T20 Cozinha"
  ip            TEXT NOT NULL,
  porta         INT  NOT NULL DEFAULT 9100,       -- RAW/ESC-POS por TCP na LAN
  papel_mm      SMALLINT NOT NULL DEFAULT 80,
  ativa         BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE categoria (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        TEXT NOT NULL,                      -- Entradas, Massas, Bebidas...
  estacao_id  BIGINT REFERENCES estacao (id),     -- p/ onde esta categoria imprime por padrão
  sort        INT NOT NULL DEFAULT 0,
  ativo       BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX ux_categoria_nome ON categoria (lower(nome)) WHERE ativo;

CREATE TABLE produto (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome                 TEXT NOT NULL,
  descricao            TEXT,
  categoria_id         BIGINT NOT NULL REFERENCES categoria (id),
  preco                NUMERIC(12,2) NOT NULL CHECK (preco >= 0),
  -- override da estação da categoria (ex.: "Batata Frita" sai na cozinha,
  -- mas "Porção do Bar" imprime no bar)
  estacao_id           BIGINT REFERENCES estacao (id),
  -- produtos SEM ficha técnica que são o próprio insumo (long neck, lata de
  -- refrigerante, garrafa de água): a venda dá baixa 1:1 neste insumo.
  insumo_vinculado_id  BIGINT REFERENCES insumo (id),
  unidade_porcao       TEXT,                       -- "prato ~350 g", "copo 300 ml"
  ativo                BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_produto_nome ON produto (lower(nome)) WHERE ativo;

-- Cabeçalho da ficha técnica (1 por produto)
CREATE TABLE ficha_tecnica (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produto_id     BIGINT NOT NULL UNIQUE REFERENCES produto (id) ON DELETE CASCADE,
  rendimento     NUMERIC(12,3) NOT NULL DEFAULT 1,   -- quantas porções a receita rende
  unidade_rendimento TEXT,                           -- "porções", "litros"
  observacoes    TEXT,
  atualizado_em  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Ingredientes da ficha. QUANTIDADE sempre na UNIDADE DE ESTOQUE do insumo
-- (0,250 = 250 g de picanha LÍQUIDA). perca_pct = desperdício de pré-preparo
-- (descasca, ossos): a baixa no estoque usa a quantidade BRUTA = liq/(1-perca).
CREATE TABLE ficha_tecnica_item (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ficha_tecnica_id   BIGINT NOT NULL REFERENCES ficha_tecnica (id) ON DELETE CASCADE,
  insumo_id          BIGINT NOT NULL REFERENCES insumo (id),
  quantidade         NUMERIC(12,3) NOT NULL CHECK (quantidade > 0),
  perca_pct        NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (perca_pct BETWEEN 0 AND 99),
  observacao         TEXT                            -- "limpar e picar brunoise", "usar a clara também"
);
CREATE INDEX ix_ft_item_insumo ON ficha_tecnica_item (insumo_id);

-- ----------------------------------------------------------------------------
-- 4. MÓDULO ATENDIMENTO (GARÇOM)
-- ----------------------------------------------------------------------------
CREATE TABLE area (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome   TEXT NOT NULL UNIQUE                       -- Salão, Varanda, Mezanino, Delivery
);

CREATE TABLE mesa (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero      INT  NOT NULL,
  area_id     BIGINT NOT NULL REFERENCES area (id),
  capacidade  SMALLINT NOT NULL DEFAULT 4 CHECK (capacidade > 0),
  status      tipo_status_mesa NOT NULL DEFAULT 'LIVRE',
  -- coordenadas p/ o mapa visual (grid da tela do salão)
  pos_x       SMALLINT,
  pos_y       SMALLINT,
  ativo       BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX ux_mesa_numero ON mesa (numero) WHERE ativo;

CREATE TABLE pedido (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mesa_id        BIGINT NOT NULL REFERENCES mesa (id),
  garcom_id      BIGINT REFERENCES usuario (id),
  status         tipo_status_pedido NOT NULL DEFAULT 'ABERTO',
  observacao     TEXT,                               -- "aniversário", "cliente com pressa"
  aberto_em      TIMESTAMPTZ NOT NULL DEFAULT now(), -- início do tempo de ocupação
  fechado_em     TIMESTAMPTZ
);
-- Garante: no máximo UM pedido aberto por mesa
CREATE UNIQUE INDEX ux_pedido_aberto_mesa ON pedido (mesa_id) WHERE status = 'ABERTO';
CREATE INDEX ix_pedido_status ON pedido (status, aberto_em);

-- Remessa = "onda" de envio (1ª: entradas, 2ª: pratos, 3ª: sobremesas).
-- É o que separa o pedido POR TEMPO na cozinha e vira o "cabeçalho" impresso.
CREATE TABLE remessa (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id    BIGINT NOT NULL REFERENCES pedido (id),
  tipo         tipo_remessa NOT NULL DEFAULT 'LIVRE',
  status       tipo_status_remessa NOT NULL DEFAULT 'ENVIADA',
  enviado_em   TIMESTAMPTZ NOT NULL DEFAULT now(),
  enviado_por  BIGINT REFERENCES usuario (id),
  motivo       TEXT                                  -- motivo do cancelamento da remessa inteira
);
CREATE INDEX ix_remessa_pedido ON remessa (pedido_id);

CREATE TABLE pedido_item (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id        BIGINT NOT NULL REFERENCES pedido (id),
  remessa_id       BIGINT REFERENCES remessa (id),   -- NULL = ainda rascunho do garçom, não impresso
  produto_id       BIGINT NOT NULL REFERENCES produto (id),
  quantidade       NUMERIC(12,3) NOT NULL CHECK (quantidade > 0),
  preco_unitario   NUMERIC(12,2) NOT NULL,           -- snapshot do preço no lançamento
  status           tipo_status_item NOT NULL DEFAULT 'RASCUNHO',
  -- Observações livres: "carne ao ponto", "sem cebola", "ponto da batata"
  observacao       TEXT,
  -- Atributos estruturados mais comuns em restaurante (sabor de massa, ponto
  -- da carne etc.). NULL usa o padrão da categoria/produto.
  ponto_carne      TEXT,
  motivo_cancelamento TEXT,
  criado_em        TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_por   BIGINT REFERENCES usuario (id)    -- quem mudou o status (p/ atribuir gorjeta)
);
CREATE INDEX ix_item_pedido  ON pedido_item (pedido_id);
CREATE INDEX ix_item_remessa ON pedido_item (remessa_id) WHERE remessa_id IS NOT NULL;
CREATE INDEX ix_item_status  ON pedido_item (status);

ALTER TABLE estoque_movimento
  ADD CONSTRAINT fk_estoque_mov_pedido_item
  FOREIGN KEY (pedido_item_id) REFERENCES pedido_item (id);

-- Fila/registro de impressão (o "print agent" local consome esta fila e
-- marca IMPRESSA/FALHA com tentativas — reimpressão vira novo log).
-- Um job por (remessa, estação): itens de cozinha e bar na mesma remessa
-- geram jobs separados automaticamente.
CREATE TABLE impressao_log (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  remessa_id       BIGINT NOT NULL REFERENCES remessa (id),
  estacao_id       BIGINT NOT NULL REFERENCES estacao (id),
  -- PRODUCAO = comanda normal · CANCELAMENTO = ticket avulso quando um item
  -- já enviado é cancelado (a cozinha precisa ver, mesmo que já tenha impresso)
  tipo             TEXT NOT NULL DEFAULT 'PRODUCAO'
                   CHECK (tipo IN ('PRODUCAO', 'CANCELAMENTO')),
  -- EM_IMPRESSAO = claimed por um print-agent (evita impressão duplicada
  -- quando há 2 agentes; claims travados >5 min podem ser retomados).
  status           tipo_status_impressao NOT NULL DEFAULT 'PENDENTE',
  conteudo         TEXT,                    -- comanda renderizada (texto/ESC-POS) montada pelo backend
  tentativas       INT NOT NULL DEFAULT 0,
  criado_em        TIMESTAMPTZ NOT NULL DEFAULT now(),
  ultima_tentativa TIMESTAMPTZ
);
CREATE INDEX ix_impressao_fila ON impressao_log (status, criado_em) WHERE status = 'PENDENTE';
-- Idempotência: no máximo 1 job ativo (pendente ou sendo impresso) por
-- (remessa, estação, tipo). PRODUCAO e CANCELAMENTO coexistem; reimpressão
-- manual cria outro PRODUCAO quando não há job ativo.
CREATE UNIQUE INDEX ux_impressao_job ON impressao_log (remessa_id, estacao_id, tipo)
  WHERE status IN ('PENDENTE', 'EM_IMPRESSAO');

-- ----------------------------------------------------------------------------
-- 5. MÓDULO CONTAS / CAIXA
-- ----------------------------------------------------------------------------
-- Conta = "ponta" da mesa. Uma mesa pode ter N contas quando dividida
-- (divisão por item) — e cada conta aceita N pagamentos.
CREATE TABLE conta (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id        BIGINT NOT NULL REFERENCES pedido (id),
  descricao        TEXT NOT NULL DEFAULT 'Conta 1',  -- "Conta 1 - João", "4ª parte"
  status           tipo_status_conta NOT NULL DEFAULT 'ABERTA',
  incluir_servico  BOOLEAN NOT NULL DEFAULT TRUE,    -- 10% do garçom
  servico_pct      NUMERIC(5,2) NOT NULL DEFAULT 10.00
                   CHECK (servico_pct BETWEEN 0 AND 100), -- snapshot da config
  desconto_valor   NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (desconto_valor >= 0),
  -- DIVISÃO IGUALITÁRIA: quando preenchido, o total desta conta É este
  -- valor (serviço/desconto já embutidos pelo app). Division por item usa
  -- conta_item e deixa este campo NULL.
  valor_rateio     NUMERIC(12,2),
  aberto_em        TIMESTAMPTZ NOT NULL DEFAULT now(),
  fechada_em       TIMESTAMPTZ,
  CHECK (valor_rateio IS NULL OR valor_rateio >= 0)
);
CREATE INDEX ix_conta_pedido ON conta (pedido_id);
CREATE INDEX ix_conta_status ON conta (status);

-- Divisão POR ITEM: quais itens (e quantas unidades deles) pertencem a esta
-- conta. Permite até rachar 1 prato 8x8 em 2 contas (quantidade fracionária).
CREATE TABLE conta_item (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conta_id       BIGINT NOT NULL REFERENCES conta (id) ON DELETE CASCADE,
  pedido_item_id BIGINT NOT NULL REFERENCES pedido_item (id),
  quantidade     NUMERIC(12,3) NOT NULL DEFAULT 1 CHECK (quantidade > 0)
);
CREATE UNIQUE INDEX ux_conta_item ON conta_item (conta_id, pedido_item_id);
CREATE INDEX ix_conta_item_item ON conta_item (pedido_item_id);

CREATE TABLE caixa (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operador_id    BIGINT NOT NULL REFERENCES usuario (id),
  status         tipo_status_caixa NOT NULL DEFAULT 'ABERTO',
  valor_inicial  NUMERIC(12,2) NOT NULL DEFAULT 0,   -- fundo de troco
  aberto_em      TIMESTAMPTZ NOT NULL DEFAULT now(),
  fechado_em     TIMESTAMPTZ,
  valor_contado  NUMERIC(12,2),                       -- digitado na conferência
  diferenca      NUMERIC(12,2),                       -- contado - esperado (calculado no fechamento)
  observacao     TEXT
);
-- 1 caixa aberto por operador (a API também checa e devolve 409 amigável)
CREATE UNIQUE INDEX ux_caixa_aberto_operador ON caixa (operador_id) WHERE status = 'ABERTO';

CREATE TABLE caixa_movimento (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caixa_id    BIGINT NOT NULL REFERENCES caixa (id),
  tipo        tipo_movimento_caixa NOT NULL,          -- SANGRIA | SUPRIMENTO
  valor       NUMERIC(12,2) NOT NULL CHECK (valor > 0),
  motivo      TEXT,
  usuario_id  BIGINT REFERENCES usuario (id),
  criado_em   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE pagamento (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conta_id     BIGINT NOT NULL REFERENCES conta (id),
  caixa_id     BIGINT REFERENCES caixa (id),          -- caixa do operador no momento do pagamento
  forma        tipo_forma_pagamento NOT NULL,
  status       tipo_status_pagamento NOT NULL DEFAULT 'APROVADO', -- PIX/PIX-retorno inicia PENDENTE
  valor        NUMERIC(12,2) NOT NULL CHECK (valor > 0),
  -- troco < valor (líquido sempre positivo — espelha a validação da API)
  valor_troco  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (valor_troco >= 0 AND valor_troco < valor),
  referencia   TEXT,                                  -- id Pix/cartão (copia-e-cola do app do banco)
  observacao   TEXT,
  pago_em      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_pagamento_caixa ON pagamento (caixa_id, pago_em) WHERE status = 'APROVADO';
CREATE INDEX ix_pagamento_conta ON pagamento (conta_id);

