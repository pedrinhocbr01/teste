-- Soma dos movimentos → saldo atual por insumo
CREATE VIEW vw_saldo_insumo AS
SELECT
  i.id AS insumo_id,
  i.nome,
  um.sigla AS unidade,
  COALESCE(SUM(CASE
    WHEN m.tipo IN ('ENTRADA', 'AJUSTE_POSITIVO') THEN  m.quantidade
    ELSE -m.quantidade
  END), 0) AS saldo
FROM insumo i
JOIN unidade_medida um ON um.id = i.unidade_estoque_id
LEFT JOIN estoque_movimento m ON m.insumo_id = i.id
WHERE i.ativo
GROUP BY i.id, i.nome, um.sigla;

-- Alertas de estoque mínimo com métricas de "quantos dias aguento"
CREATE VIEW vw_alerta_estoque AS
WITH consumo AS (
  SELECT m.insumo_id,
         SUM(CASE WHEN m.tipo IN ('SAIDA_VENDA','CONSUMO_INTERNO','PERDA')
                  THEN m.quantidade ELSE 0 END) AS consumo_30d
  FROM estoque_movimento m
  WHERE m.data_movimento >= now() - INTERVAL '30 days'
  GROUP BY m.insumo_id
)
SELECT
  s.insumo_id,
  s.nome,
  s.unidade,
  s.saldo,
  i.estoque_minimo,
  c.consumo_30d,
  CASE WHEN c.consumo_30d > 0
       THEN ROUND(s.saldo / (c.consumo_30d / 30.0), 1)
  END AS dias_de_estoque,
  CASE
    WHEN s.saldo <= 0                                    THEN 'SEM_SALDO'
    WHEN s.saldo <= i.estoque_minimo                     THEN 'ABAIXO_DO_MINIMO'
    WHEN c.consumo_30d > 0 AND s.saldo / (c.consumo_30d/30.0) < 3 THEN 'COMPRA_URGENTE'
    ELSE 'OK'
  END AS nivel,
  GREATEST(COALESCE(i.estoque_maximo, i.estoque_minimo * 3) - s.saldo, 0) AS compra_sugerida
FROM vw_saldo_insumo s
JOIN insumo i ON i.id = s.insumo_id
LEFT JOIN consumo c ON c.insumo_id = s.insumo_id;

-- Custo e margem reais de cada prato (considera a PERCA da ficha técnica)
CREATE VIEW vw_custo_produto AS
SELECT
  p.id AS produto_id,
  p.nome,
  p.preco,
  ROUND(COALESCE(SUM(
        (fti.quantidade / (1 - fti.perca_pct / 100.0)) * i.custo_unitario
      ), 0) / GREATEST(f.rendimento, 1), 2) AS custo_por_porcao,
  CASE WHEN p.preco > 0
       THEN ROUND((p.preco - COALESCE(SUM(
              (fti.quantidade / (1 - fti.perca_pct / 100.0)) * i.custo_unitario
            ), 0) / GREATEST(f.rendimento, 1)) / p.preco * 100, 1)
  END AS margem_pct
FROM produto p
LEFT JOIN ficha_tecnica f     ON f.produto_id = p.id
LEFT JOIN ficha_tecnica_item fti ON fti.ficha_tecnica_id = f.id
LEFT JOIN insumo i            ON i.id = fti.insumo_id
WHERE p.ativo
GROUP BY p.id, p.nome, p.preco, f.rendimento;

-- Visão do mapa de mesas: status + tempo de ocupação em minutos
CREATE VIEW vw_mapa_mesas AS
SELECT
  m.id AS mesa_id,
  m.numero,
  a.nome AS area,
  m.capacidade,
  m.status,
  m.pos_x, m.pos_y,
  pr.id AS pedido_id,
  u.nome AS garcom,
  pr.aberto_em,
  CASE WHEN pr.id IS NOT NULL
       THEN FLOOR(EXTRACT(EPOCH FROM (now() - pr.aberto_em)) / 60)
  END AS ocupacao_min
FROM mesa m
JOIN area a ON a.id = m.area_id
LEFT JOIN pedido pr ON pr.mesa_id = m.id AND pr.status = 'ABERTO'
LEFT JOIN usuario u ON u.id = pr.garcom_id
WHERE m.ativo;

-- Resumo de cada conta: subtotal (dos itens ou do rateio), serviço, saldo.
-- Rateio: o valor fechado JÁ inclui base+serviço — o servico_valor é DERIVADO
-- (rateio × pct/(100+pct)) para o recibo mostrar os 10% e a gorjeta do
-- garçom não zerar na divisão igualitária. Total nunca negativo (desconto
-- acima do subtotal zera a conta em vez de gerar saldo negativo).
CREATE VIEW vw_conta_resumo AS
WITH base AS (
  SELECT c.*,
         COALESCE(SUM(ci.quantidade * pi.preco_unitario), 0) AS sub_itens,
         -- subquery escalar: 1 linha por conta (JOIN+GROUP BY duplicaria o pago)
         COALESCE((SELECT SUM(pg.valor - pg.valor_troco) FROM pagamento pg
                   WHERE pg.conta_id = c.id AND pg.status = 'APROVADO'), 0) AS pago
  FROM conta c
  LEFT JOIN conta_item ci ON ci.conta_id = c.id
  LEFT JOIN pedido_item pi ON pi.id = ci.pedido_item_id AND pi.status <> 'CANCELADO'
  WHERE c.status <> 'CANCELADA'
  GROUP BY c.id
),
tot AS (
  SELECT b.*,
    CASE WHEN b.valor_rateio IS NOT NULL THEN
           CASE WHEN b.incluir_servico
                THEN ROUND(b.valor_rateio * b.servico_pct / (100 + b.servico_pct), 2)
                ELSE 0 END
         WHEN b.incluir_servico THEN ROUND(b.sub_itens * b.servico_pct / 100, 2)
         ELSE 0
    END AS servico_valor
  FROM base b
)
SELECT
  id AS conta_id,
  pedido_id,
  descricao,
  status,
  CASE WHEN valor_rateio IS NOT NULL THEN 0 ELSE ROUND(sub_itens, 2) END AS subtotal_itens,
  valor_rateio,
  servico_valor,
  desconto_valor,
  GREATEST(ROUND(CASE WHEN valor_rateio IS NOT NULL THEN valor_rateio
                      ELSE sub_itens + servico_valor END, 2) - desconto_valor, 0) AS total,
  pago,
  GREATEST(ROUND(CASE WHEN valor_rateio IS NOT NULL THEN valor_rateio
                      ELSE sub_itens + servico_valor END, 2) - desconto_valor, 0) - pago AS saldo
FROM tot;

-- Fechamento de caixa: esperado por forma vs. digitado.
-- Usa subqueries escalares (NUNCA joins com GROUP BY aqui: pagamento ×
-- caixa_movimento formaria produto cartesiano e duplicaria os totais).
CREATE VIEW vw_caixa_resumo AS
SELECT
  cx.id AS caixa_id,
  u.nome AS operador,
  cx.status,
  cx.aberto_em,
  cx.valor_inicial,
  COALESCE((SELECT SUM(p.valor - p.valor_troco) FROM pagamento p
            WHERE p.caixa_id = cx.id AND p.status='APROVADO' AND p.forma='DINHEIRO'), 0)      AS dinheiro,
  COALESCE((SELECT SUM(p.valor) FROM pagamento p
            WHERE p.caixa_id = cx.id AND p.status='APROVADO' AND p.forma='PIX'), 0)           AS pix,
  COALESCE((SELECT SUM(p.valor) FROM pagamento p
            WHERE p.caixa_id = cx.id AND p.status='APROVADO' AND p.forma='CARTAO_CREDITO'), 0) AS cartao_credito,
  COALESCE((SELECT SUM(p.valor) FROM pagamento p
            WHERE p.caixa_id = cx.id AND p.status='APROVADO' AND p.forma='CARTAO_DEBITO'), 0)  AS cartao_debito,
  COALESCE((SELECT SUM(p.valor) FROM pagamento p
            WHERE p.caixa_id = cx.id AND p.status='APROVADO'
              AND p.forma IN ('VALE_ALIMENTACAO','VALE_REFEICAO')), 0)                          AS vales,
  COALESCE((SELECT SUM(p.valor) FROM pagamento p
            WHERE p.caixa_id = cx.id AND p.status='APROVADO' AND p.forma='OUTRO'), 0)          AS outros,
  COALESCE((SELECT SUM(p.valor - p.valor_troco) FROM pagamento p
            WHERE p.caixa_id = cx.id AND p.status='APROVADO'), 0)                              AS total_vendido,
  COALESCE((SELECT SUM(k.valor) FROM caixa_movimento k
            WHERE k.caixa_id = cx.id AND k.tipo='SUPRIMENTO'), 0)                              AS suprimentos,
  COALESCE((SELECT SUM(k.valor) FROM caixa_movimento k
            WHERE k.caixa_id = cx.id AND k.tipo='SANGRIA'), 0)                                AS sangrias,
  cx.valor_inicial
    + COALESCE((SELECT SUM(p.valor - p.valor_troco) FROM pagamento p
                WHERE p.caixa_id = cx.id AND p.status='APROVADO'), 0)
    + COALESCE((SELECT SUM(k.valor) FROM caixa_movimento k
                WHERE k.caixa_id = cx.id AND k.tipo='SUPRIMENTO'), 0)
    - COALESCE((SELECT SUM(k.valor) FROM caixa_movimento k
                WHERE k.caixa_id = cx.id AND k.tipo='SANGRIA'), 0)                             AS valor_esperado,
  -- conferência da GAVETA: só o que é físico (fundo + dinheiro − trocos +
  -- suprimentos − sangrias). Cartão/PIX conferem pelo extrato da adquirente.
  cx.valor_inicial
    + COALESCE((SELECT SUM(p.valor - p.valor_troco) FROM pagamento p
                WHERE p.caixa_id = cx.id AND p.status='APROVADO' AND p.forma='DINHEIRO'), 0)
    + COALESCE((SELECT SUM(k.valor) FROM caixa_movimento k
                WHERE k.caixa_id = cx.id AND k.tipo='SUPRIMENTO'), 0)
    - COALESCE((SELECT SUM(k.valor) FROM caixa_movimento k
                WHERE k.caixa_id = cx.id AND k.tipo='SANGRIA'), 0)                             AS valor_esperado_dinheiro,
  cx.valor_contado,
  cx.diferenca
FROM caixa cx
JOIN usuario u ON u.id = cx.operador_id;

-- Gorjeta a repassar por garçom (soma do serviço das contas fechadas)
CREATE VIEW vw_gorjeta_garcom AS
SELECT
  u.id AS garcom_id,
  u.nome,
  DATE_TRUNC('month', pr.fechado_em)::date AS mes,
  ROUND(SUM(vcr.servico_valor), 2) AS gorjeta_total
FROM conta c
JOIN vw_conta_resumo vcr ON vcr.conta_id = c.id
JOIN pedido pr ON pr.id = c.pedido_id AND pr.status = 'FECHADO'
JOIN usuario u ON u.id = pr.garcom_id
WHERE c.status = 'FECHADA' AND c.incluir_servico
GROUP BY u.id, u.nome, DATE_TRUNC('month', pr.fechado_em);

