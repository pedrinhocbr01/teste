-- 7.1 Baixa automática de estoque na venda (e estorno no cancelamento).
-- Regra: deduz BRUTO = quantidade/(1 - perca%) da ficha, por unidade vendida.
-- O ponto de acionamento respeita config_restaurante.baixa_estoque_em.
CREATE OR REPLACE FUNCTION fn_item_baixa_estoque() RETURNS trigger AS $$
DECLARE
  v_baixa_em   TEXT;
  v_ja_baixado BOOLEAN;
BEGIN
  SELECT cfg.baixa_estoque_em INTO v_baixa_em FROM config_restaurante cfg WHERE cfg.id = 1;
  v_baixa_em := COALESCE(v_baixa_em, 'ENVIO');

  -- Estorno: item que JÁ baixou estoque foi cancelado
  IF TG_OP = 'UPDATE'
     AND NEW.status = 'CANCELADO' AND OLD.status <> 'CANCELADO' THEN
    INSERT INTO estoque_movimento
      (insumo_id, tipo, quantidade, custo_unitario, origem, pedido_item_id, usuario_id, motivo)
    SELECT m.insumo_id, 'AJUSTE_POSITIVO'::tipo_movimento_estoque, m.quantidade, m.custo_unitario,
           'CANCELAMENTO_ITEM'::tipo_origem_movimento, NEW.id, NEW.atualizado_por,
           'Estorno: item #' || NEW.id || ' cancelado (estava ' || OLD.status || ')'
    FROM estoque_movimento m
    WHERE m.pedido_item_id = NEW.id AND m.tipo = 'SAIDA_VENDA';
    RETURN NULL;
  END IF;

  IF NEW.status IN ('ENVIADO', 'EM_PREPARO', 'PRONTO', 'ENTREGUE') THEN
    SELECT EXISTS (
      SELECT 1 FROM estoque_movimento m
      WHERE m.pedido_item_id = NEW.id AND m.tipo = 'SAIDA_VENDA'
    ) INTO v_ja_baixado;

    IF NOT v_ja_baixado THEN
      IF (v_baixa_em = 'ENVIO')
         OR (v_baixa_em = 'PRONTO'   AND NEW.status IN ('PRONTO', 'ENTREGUE'))
         OR (v_baixa_em = 'ENTREGA'  AND NEW.status = 'ENTREGUE') THEN

        -- 1) Via ficha técnica (pratos): baixa BRUTA, proporcional ao
        --    rendimento da receita (1 fatia de um pudim q rende 10 baixa 1/10)
        INSERT INTO estoque_movimento
          (insumo_id, tipo, quantidade, custo_unitario, origem, pedido_item_id, usuario_id, motivo)
        SELECT fti.insumo_id,
               'SAIDA_VENDA'::tipo_movimento_estoque,
               ROUND(fti.quantidade / (1 - fti.perca_pct / 100.0)
                     * NEW.quantidade / GREATEST(f.rendimento, 1), 3),
               i.custo_unitario,
               'BAIXA_VENDA'::tipo_origem_movimento,
               NEW.id,
               NEW.atualizado_por,
               'Venda: ' || p.nome || ' x' || NEW.quantidade
        FROM produto p
        JOIN ficha_tecnica f      ON f.produto_id = p.id
        JOIN ficha_tecnica_item fti ON fti.ficha_tecnica_id = f.id
        JOIN insumo i             ON i.id = fti.insumo_id
        WHERE p.id = NEW.produto_id
        UNION ALL
        -- 2) Produto vinculado 1:1 a um insumo (bebidas fechadas etc.)
        SELECT p.insumo_vinculado_id,
               'SAIDA_VENDA',
               NEW.quantidade,
               i.custo_unitario,
               'BAIXA_VENDA'::tipo_origem_movimento,
               NEW.id,
               NEW.atualizado_por,
               'Venda: ' || p.nome || ' x' || NEW.quantidade
        FROM produto p
        JOIN insumo i ON i.id = p.insumo_vinculado_id
        WHERE p.id = NEW.produto_id
          AND p.insumo_vinculado_id IS NOT NULL
          AND NOT EXISTS (SELECT 1 FROM ficha_tecnica f WHERE f.produto_id = p.id);
      END IF;
    END IF;
  END IF;

  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_item_baixa_estoque
AFTER INSERT OR UPDATE OF status ON pedido_item
FOR EACH ROW EXECUTE FUNCTION fn_item_baixa_estoque();

-- 7.2 Envio de itens → enfileira UM job de impressão por (remessa, estação).
-- Dispara no pedido_item (não na remessa): quando o garçom aperta "enviar",
-- os itens passam a ENVIADO e cada estação envolvida (cozinha E/OU bar)
-- ganha seu próprio job, mesmo dentro da mesma remessa. O print agent da LAN
-- consome a fila e imprime via ESC/POS. Impresso é um novo job manual.
CREATE OR REPLACE FUNCTION fn_item_fila_impressao() RETURNS trigger AS $$
DECLARE
  v_estacao BIGINT;
BEGIN
  IF NEW.status = 'ENVIADO'
     AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM 'ENVIADO')
     AND NEW.remessa_id IS NOT NULL THEN

    -- resolve a estação do produto: override do produto > padrão da categoria
    SELECT COALESCE(p.estacao_id, cat.estacao_id) INTO v_estacao
    FROM produto p
    JOIN categoria cat ON cat.id = p.categoria_id
    WHERE p.id = NEW.produto_id;

    IF v_estacao IS NOT NULL THEN
      INSERT INTO impressao_log (remessa_id, estacao_id, tipo)
      VALUES (NEW.remessa_id, v_estacao, 'PRODUCAO')
      ON CONFLICT (remessa_id, estacao_id, tipo) WHERE status IN ('PENDENTE', 'EM_IMPRESSAO')
      DO NOTHING;   -- já existe job ativo p/ esta estação nesta remessa
    END IF;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_item_fila_impressao
AFTER INSERT OR UPDATE OF status ON pedido_item
FOR EACH ROW EXECUTE FUNCTION fn_item_fila_impressao();

-- 7.2b Cancelamento de item enviado → ticket de CANCELAMENTO na estação certa.
-- (Fase 2: a cozinha/bar precisa VER o cancelamento, mesmo que já tenha
-- impresso a comanda original — o print-agent imprime este ticket avulso.)
-- Vários cancelamentos da mesma (remessa, estação) acumulam num único ticket
-- pendente (conteúdo concatenado) em vez de um papel para cada item.
CREATE OR REPLACE FUNCTION fn_item_fila_cancelamento() RETURNS trigger AS $$
DECLARE
  v_estacao BIGINT;
  v_texto   TEXT;
BEGIN
  IF NEW.status = 'CANCELADO'
     AND OLD.status IN ('ENVIADO', 'EM_PREPARO', 'PRONTO', 'ENTREGUE')
     AND NEW.remessa_id IS NOT NULL THEN

    SELECT COALESCE(p.estacao_id, cat.estacao_id) INTO v_estacao
    FROM produto p
    JOIN categoria cat ON cat.id = p.categoria_id
    WHERE p.id = NEW.produto_id;

    IF v_estacao IS NOT NULL THEN
      SELECT 'CANCELADO: ' || NEW.quantidade::TEXT || 'x ' || p.nome ||
             COALESCE(' — ' || NULLIF(NEW.motivo_cancelamento, ''), '')
      INTO v_texto
      FROM produto p WHERE p.id = NEW.produto_id;

      INSERT INTO impressao_log (remessa_id, estacao_id, tipo, conteudo)
      VALUES (NEW.remessa_id, v_estacao, 'CANCELAMENTO', v_texto)
      ON CONFLICT (remessa_id, estacao_id, tipo) WHERE status IN ('PENDENTE', 'EM_IMPRESSAO')
      DO UPDATE SET conteudo = impressao_log.conteudo || E'\n' || EXCLUDED.conteudo;
    END IF;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_item_fila_cancelamento
AFTER UPDATE OF status ON pedido_item
FOR EACH ROW EXECUTE FUNCTION fn_item_fila_cancelamento();

-- 7.3 Ciclo de vida da mesa: abrir pedido ocupa; fechar/cancelar libera.
-- (AGUARDANDO_CONTA é definido pelo app quando o garçom/caixa imprime a conta)
CREATE OR REPLACE FUNCTION fn_pedido_status_mesa() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    UPDATE mesa SET status = 'OCUPADA' WHERE id = NEW.mesa_id;
  ELSIF TG_OP = 'UPDATE' AND NEW.status <> 'ABERTO' AND OLD.status = 'ABERTO' THEN
    UPDATE mesa SET status = 'LIVRE' WHERE id = NEW.mesa_id;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_pedido_status_mesa
AFTER INSERT OR UPDATE OF status ON pedido
FOR EACH ROW EXECUTE FUNCTION fn_pedido_status_mesa();

-- 7.4 Rateio por item: proíbe alocar mais unidades do que foi pedido
CREATE OR REPLACE FUNCTION fn_valida_rateio_itens() RETURNS trigger AS $$
DECLARE
  v_total NUMERIC(12,3);
  v_pedido NUMERIC(12,3);
BEGIN
  SELECT COALESCE(SUM(ci.quantidade), 0) INTO v_total
  FROM conta_item ci
  WHERE ci.pedido_item_id = NEW.pedido_item_id;

  SELECT pi.quantidade INTO v_pedido FROM pedido_item pi WHERE pi.id = NEW.pedido_item_id;

  IF v_total > v_pedido THEN
    RAISE EXCEPTION 'Rateio excede o item: % unidade(s) alocadas de %', v_total, v_pedido
      USING HINT = 'Ajuste as quantidades nas contas da mesa.';
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_valida_rateio_itens
AFTER INSERT OR UPDATE ON conta_item
FOR EACH ROW EXECUTE FUNCTION fn_valida_rateio_itens();

-- 7.5 Atualiza atualizado_em do item (dispara baixa/cancelamento com data certa)
CREATE OR REPLACE FUNCTION fn_touch_pedido_item() RETURNS trigger AS $$
BEGIN
  NEW.atualizado_em := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_touch_pedido_item
BEFORE UPDATE ON pedido_item
FOR EACH ROW EXECUTE FUNCTION fn_touch_pedido_item();

